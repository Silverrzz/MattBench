const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { spawn } = require('node:child_process');

(async () => {
    const server = spawn(process.env.PYTHON || path.resolve('bin/python'), ['Scripts/test_training_datasets_browser.py']);
    server.stderr.on('data', data => process.stderr.write(data));
    const url = await new Promise((resolve, reject) => {
        server.stdout.once('data', data => resolve(data.toString().trim()));
        server.once('exit', code => reject(new Error('Fixture server exited: ' + code)));
    });
    let browser;
    try {
        browser = await chromium.launch({headless: true});
        const page = await browser.newPage({viewport: {width: 1280, height: 1000}});
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.goto(url);
        const selections = () => page.locator('#train-stage_datasets').evaluate(input => JSON.parse(input.value));
        const rows = page.locator('.training-stage-row');
        await rows.first().locator('.dataset-picker-trigger').waitFor();
        const workload = page.locator('#train-workload_size');
        const workloadHelp = page.locator('#training-workload-help');
        await page.locator('#training-run-settings').evaluate(details => { details.open = true; });
        assert.equal(await workload.inputValue(), '0');
        assert.equal(await workload.evaluate(input => input.readOnly), false);
        assert.match(await workloadHelp.innerText(), /Default: uninterrupted/);
        await page.locator('#train-schedule').selectOption('other');
        assert.equal(await workload.inputValue(), '0');
        assert.equal(await workload.evaluate(input => input.readOnly), true);
        assert.match(await workloadHelp.innerText(), /requires uninterrupted training/);
        await page.locator('#train-schedule').selectOption('schedule');
        assert.equal(await workload.inputValue(), '0');
        await workload.fill('25');
        await page.locator('#train-schedule').selectOption('other');
        assert.equal(await workload.inputValue(), '0');
        await page.locator('#train-schedule').selectOption('schedule');
        assert.equal(await workload.inputValue(), '25');
        await workload.fill('0');
        assert.deepEqual(await selections(), [{stage: 0, datasets: ['a']}, {stage: 1, datasets: ['b']}]);
        await rows.first().locator('.dataset-picker-trigger').click();
        await rows.first().locator('.dataset-picker-search').fill('Beta');
        await rows.first().getByRole('option', {name: /Beta/}).click();
        assert.deepEqual((await selections())[0].datasets, ['a', 'b']);
        assert.equal(await rows.first().locator('.dataset-picker-panel').isVisible(), true);
        await rows.first().getByRole('button', {name: 'Done', exact: true}).click();
        assert.equal(await rows.first().locator('.dataset-picker-selections li').count(), 2);
        await page.locator('#train-schedule').selectOption('other');
        assert.equal(await rows.count(), 1);
        await page.locator('#train-schedule').selectOption('schedule');
        assert.deepEqual((await selections())[0].datasets, ['a', 'b']);
        await rows.first().getByRole('button', {name: 'Remove Beta'}).click();
        assert.deepEqual((await selections())[0].datasets, ['a']);
        await rows.first().locator('.dataset-picker-trigger').click();
        await rows.first().locator('.dataset-picker-search').fill('Alpha');
        await rows.first().locator('.dataset-picker-search').press('Enter');
        assert.deepEqual((await selections())[0].datasets, []);
        assert.equal(await rows.first().locator('select').evaluate(input => input.validity.valueMissing), true);
        await rows.first().locator('.dataset-picker-search').press('Escape');
        await page.locator('#train-checkpoint').selectOption('checkpoint');
        assert.equal(await workload.inputValue(), '0');
        assert.equal(await workload.evaluate(input => input.readOnly), false);
        assert.deepEqual(await selections(), [{stage: 0, datasets: ['a', 'c']}, {stage: 1, datasets: ['b', 'c']}]);
        assert.match(await rows.first().locator('.training-stage-label').innerText(), /already completed/);
        await page.screenshot({path: '/tmp/mattbench-multi-datasets.png', fullPage: true});
        await page.setViewportSize({width: 390, height: 844});
        await rows.nth(1).locator('.dataset-picker-trigger').click();
        await rows.nth(1).locator('.dataset-picker-search').fill('Gamma');
        await rows.nth(1).locator('.dataset-picker-search').press('Enter');
        assert.deepEqual((await selections())[1].datasets, ['b']);
        await rows.nth(1).locator('.dataset-picker-search').press('Escape');
        assert.deepEqual(errors, []);
        console.log('Browser workload defaults and locking, dataset selection, validation, schedule drafts, checkpoint restoration, and mobile checks passed.');
    } finally {
        await browser?.close();
        server.kill();
    }
})().catch(error => { console.error(error); process.exitCode = 1; });
